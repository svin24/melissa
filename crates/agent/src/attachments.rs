//! Files the user sends with a chat message: validation, type sniffing, names and delivery to
//! the model. They are stored in the agent's file box ([`crate::files`]).
//!
//! - **Upload.** [`validate`] checks the limits ([`MAX_FILE_BYTES`] per file,
//!   [`MAX_MESSAGE_BYTES`] and [`MAX_FILES`] per message); [`sniff`] takes the type from the
//!   bytes (the browser's claim and the name's extension are ignored); [`safe_name`] cleans the
//!   name. [`crate::files::FileBoxes::store_uploads`] writes them into the box and returns the
//!   message's [`Attachment`]s, which go into the conversation's event, so the feed shows them
//!   after a reload. [`Attachment::file`] is `<id>.<ext>`: the id is the box file's
//!   (generated, never a name the user chose).
//! - **Serving.** By that id from the box; [`content_type`] says how to serve one.
//! - **Delivery** ([`deliver`]). Images (PNG, JPEG, GIF, WebP) and PDFs go to the model as native
//!   content blocks when the session supports them and they fit the model's limits. Every file
//!   stays in the agent's file box (which its sandbox sees) and the message lists them there,
//!   so the agent can use them with its own tools.

use std::io::Read;

use base64::Engine as _;
use serde::{Deserialize, Serialize};

use crate::{
    files::FileBoxes,
    session::{PromptBlock, SessionCapabilities},
    tools::permissions::Principal,
};

const MIB: usize = 1024 * 1024;

/// Largest single file.
pub const MAX_FILE_BYTES: usize = 20 * MIB;
/// Largest total of one message's files.
pub const MAX_MESSAGE_BYTES: usize = 50 * MIB;
/// Most files in one message.
pub const MAX_FILES: usize = 10;
/// Largest image sent to the model as an image block. Claude's API takes at most 5 MB per
/// image (base64 adds a third); larger ones go to the working directory instead.
pub const NATIVE_IMAGE_BYTES: usize = 3_750_000;
/// Largest PDF sent to the model as a document block.
pub const NATIVE_PDF_BYTES: usize = 10 * MIB;
/// Largest total of native blocks in one message (keeps the request well under the API's
/// 32 MB limit; the rest goes to the working directory).
pub const NATIVE_TOTAL_BYTES: usize = 15 * MIB;
/// Longest stored display name, in characters.
const MAX_NAME_CHARS: usize = 80;

/// A file as it arrived from the browser.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Upload {
    /// The name the browser sent (untrusted; only used, cleaned, for display).
    pub name: String,
    pub bytes: Vec<u8>,
}

/// A stored file of a message.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Attachment {
    /// The stored file's name: `<32 hex>.<ext>`, generated by Melissa.
    pub file: String,
    /// The user's name for it, cleaned by [`safe_name`].
    pub name: String,
    /// The sniffed media type.
    pub mime: String,
    pub size: u64,
}

impl Attachment {
    /// An image the browser can show (and the model can see).
    pub fn is_image(&self) -> bool {
        IMAGE_TYPES.contains(&self.mime.as_str())
    }
}

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum AttachmentError {
    #[error("{name} is larger than {} MiB", MAX_FILE_BYTES / MIB)]
    FileTooLarge { name: String },
    #[error("the files together are larger than {} MiB", MAX_MESSAGE_BYTES / MIB)]
    MessageTooLarge,
    #[error("at most {MAX_FILES} files per message")]
    TooMany,
    #[error("{name} is empty")]
    Empty { name: String },
    #[error("couldn't store {name}: {reason}")]
    Store { name: String, reason: String },
    #[error("the file box is full ({} GiB); delete some files first", crate::files::MAX_BOX_BYTES >> 30)]
    BoxFull,
}

const IMAGE_TYPES: &[&str] = &["image/png", "image/jpeg", "image/gif", "image/webp"];

/// The media type and stored extension of `bytes`, from their first bytes. Anything not
/// recognised is `application/octet-stream`; SVG and HTML are deliberately not recognised
/// (they can carry script), so they are served as downloads only.
pub fn sniff(bytes: &[u8]) -> (&'static str, &'static str) {
    let starts = |magic: &[u8]| bytes.starts_with(magic);
    if starts(b"\x89PNG\r\n\x1a\n") {
        ("image/png", "png")
    } else if starts(&[0xFF, 0xD8, 0xFF]) {
        ("image/jpeg", "jpg")
    } else if starts(b"GIF87a") || starts(b"GIF89a") {
        ("image/gif", "gif")
    } else if bytes.len() >= 12 && starts(b"RIFF") && &bytes[8..12] == b"WEBP" {
        ("image/webp", "webp")
    } else if starts(b"%PDF-") {
        ("application/pdf", "pdf")
    } else if starts(b"PK\x03\x04") {
        ("application/zip", "zip")
    } else if starts(&[0x1F, 0x8B]) {
        ("application/gzip", "gz")
    } else if looks_like_text(bytes) {
        ("text/plain", "txt")
    } else {
        ("application/octet-stream", "bin")
    }
}

/// UTF-8 without NUL bytes (judged on the first 8 KiB; a character cut at the end is fine).
fn looks_like_text(bytes: &[u8]) -> bool {
    let head = &bytes[..bytes.len().min(8192)];
    if head.contains(&0) {
        return false;
    }
    match std::str::from_utf8(head) {
        Ok(_) => true,
        // Cut inside a character at the 8 KiB boundary: still text.
        Err(e) => e.error_len().is_none() && head.len() < bytes.len(),
    }
}

/// How to serve a stored file, from its extension: the media type, and whether a browser may
/// show it inline (images only; everything else is a download).
pub fn content_type(file: &str) -> (&'static str, bool) {
    match file.rsplit_once('.').map(|(_, ext)| ext) {
        Some("png") => ("image/png", true),
        Some("jpg") => ("image/jpeg", true),
        Some("gif") => ("image/gif", true),
        Some("webp") => ("image/webp", true),
        Some("pdf") => ("application/pdf", false),
        Some("zip") => ("application/zip", false),
        Some("gz") => ("application/gzip", false),
        Some("txt") => ("text/plain; charset=utf-8", false),
        _ => ("application/octet-stream", false),
    }
}

/// A display and file name from what the browser sent: the last path component, only
/// letters, digits, `.`, `-` and `_` (other characters become `_`), no leading dot, at most
/// [`MAX_NAME_CHARS`] characters (keeping the extension), `file` if nothing is left.
pub fn safe_name(raw: &str) -> String {
    let base = raw.rsplit(['/', '\\']).next().unwrap_or("");
    let cleaned: String = base
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || matches!(c, '.' | '-' | '_') {
                c
            } else {
                '_'
            }
        })
        .collect();
    let trimmed = cleaned.trim_start_matches(['.', '_']).trim_end_matches('.');
    if trimmed.is_empty() {
        return "file".to_string();
    }
    let count = trimmed.chars().count();
    if count <= MAX_NAME_CHARS {
        return trimmed.to_string();
    }
    // Keep a short extension, shorten the stem.
    let (stem, ext) = match trimmed.rsplit_once('.') {
        Some((s, e)) if !s.is_empty() && e.chars().count() <= 10 => (s, Some(e)),
        _ => (trimmed, None),
    };
    let room = MAX_NAME_CHARS - ext.map_or(0, |e| e.chars().count() + 1);
    let stem: String = stem.chars().take(room).collect();
    match ext {
        Some(e) => format!("{stem}.{e}"),
        None => stem,
    }
}

/// Check one message's files against the limits (before anything is written).
pub fn validate(uploads: &[Upload]) -> Result<(), AttachmentError> {
    if uploads.len() > MAX_FILES {
        return Err(AttachmentError::TooMany);
    }
    let mut total = 0usize;
    for u in uploads {
        if u.bytes.is_empty() {
            return Err(AttachmentError::Empty {
                name: safe_name(&u.name),
            });
        }
        if u.bytes.len() > MAX_FILE_BYTES {
            return Err(AttachmentError::FileTooLarge {
                name: safe_name(&u.name),
            });
        }
        total += u.bytes.len();
    }
    if total > MAX_MESSAGE_BYTES {
        return Err(AttachmentError::MessageTooLarge);
    }
    Ok(())
}

/// Is `file` a name the old shared store (and [`Attachment::file`]) uses (`<32 lowercase hex>.<ext>`)?
pub fn valid_file_name(file: &str) -> bool {
    let Some((id, ext)) = file.split_once('.') else {
        return false;
    };
    id.len() == 32
        && id.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
        && (1..=5).contains(&ext.len())
        && ext
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
}

/// How one message's files reach the model.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Delivery {
    /// Content blocks for the files the model takes natively.
    pub blocks: Vec<PromptBlock>,
    /// What to add to the message text: which files came inline and where the others are.
    pub note: String,
}

/// Which files go to the model natively (by index), given what the session supports and
/// the size limits; the rest go to the working directory.
pub fn plan(files: &[Attachment], caps: &SessionCapabilities) -> Vec<bool> {
    let mut budget = NATIVE_TOTAL_BYTES as u64;
    files
        .iter()
        .map(|a| {
            let fits = if a.is_image() {
                caps.images && a.size <= NATIVE_IMAGE_BYTES as u64
            } else if a.mime == "application/pdf" {
                caps.pdfs && a.size <= NATIVE_PDF_BYTES as u64
            } else {
                false
            };
            let native = fits && a.size <= budget;
            if native {
                budget -= a.size;
            }
            native
        })
        .collect()
}

/// Turn a message's stored files (in `owner`'s file box) into content blocks and a note
/// for the agent. Every file stays in the box, where the agent can open it with its own
/// tools; the note lists them with the box's path. A file that can't be read is named in
/// the note as unavailable (the turn still runs).
pub fn deliver(
    boxes: &FileBoxes,
    owner: &Principal,
    files: &[Attachment],
    caps: &SessionCapabilities,
) -> Delivery {
    if files.is_empty() {
        return Delivery::default();
    }
    let native = plan(files, caps);
    let mut blocks = Vec::new();
    let (mut inline, mut listed, mut missing) = (Vec::new(), Vec::new(), Vec::new());
    for (a, native) in files.iter().zip(native) {
        let id = crate::files::attachment_id(&a.file);
        let opened = boxes.open_file(owner, id);
        let Ok((entry, mut file)) = opened else {
            tracing::warn!(file = %a.file, "an attachment is not in the file box");
            missing.push(a.name.clone());
            continue;
        };
        listed.push(format!(
            "{} ({}, {})",
            entry.name,
            a.mime,
            human_size(a.size)
        ));
        if !native {
            continue;
        }
        let mut bytes = Vec::new();
        match file.read_to_end(&mut bytes) {
            Ok(_) => {
                let data = base64::engine::general_purpose::STANDARD.encode(bytes);
                blocks.push(if a.is_image() {
                    PromptBlock::Image {
                        mime: a.mime.clone(),
                        data,
                    }
                } else {
                    PromptBlock::Pdf { data }
                });
                inline.push(a.name.clone());
            }
            Err(e) => tracing::warn!(file = %a.file, "reading an attachment: {e}"),
        }
    }
    let mut note = String::from("\n\n<melissa-attachments>");
    if !inline.is_empty() {
        note.push_str(&format!("\nAttached above: {}.", inline.join(", ")));
    }
    if !listed.is_empty() {
        let dir = boxes
            .dir(owner)
            .map(|d| d.display().to_string())
            .unwrap_or_default();
        note.push_str(&format!("\nThe user's files are in your file box, {dir}/:"));
        for l in &listed {
            note.push_str(&format!("\n- {l}"));
        }
    }
    if !missing.is_empty() {
        note.push_str(&format!(
            "\nThe user attached these, but they could not be passed on: {}.",
            missing.join(", ")
        ));
    }
    note.push_str("\n</melissa-attachments>");
    Delivery { blocks, note }
}

/// `1.2 MiB`, `34 KiB`, `512 B`.
pub fn human_size(bytes: u64) -> String {
    const KIB: f64 = 1024.0;
    let b = bytes as f64;
    if b >= KIB * KIB {
        format!("{:.1} MiB", b / (KIB * KIB))
    } else if b >= KIB {
        format!("{:.0} KiB", b / KIB)
    } else {
        format!("{bytes} B")
    }
}

/// Memory and disk sizes, in binary units like the rest of Melissa (`474 GiB`, `8.0 GiB`):
/// the web UI and `device_info` both use this so the chat and the pages agree.
pub fn gib_size(bytes: u64) -> String {
    let gib = bytes as f64 / (1024.0 * 1024.0 * 1024.0);
    if gib >= 10.0 {
        format!("{gib:.0} GiB")
    } else {
        format!("{gib:.1} GiB")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gib_sizes_are_binary_and_labelled_so() {
        assert_eq!(gib_size(8 * 1024 * 1024 * 1024), "8.0 GiB");
        // A "512 GB" disk: 509 GB in powers of ten, 474 GiB here.
        assert_eq!(gib_size(509_000_000_000), "474 GiB");
    }

    const PNG: &[u8] = b"\x89PNG\r\n\x1a\n\0\0\0\rIHDR";
    const PDF: &[u8] = b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n";

    fn temp_boxes(tag: &str) -> (FileBoxes, std::path::PathBuf) {
        let root = std::env::temp_dir().join(format!(
            "melissa-attach-{tag}-{}-{:?}",
            std::process::id(),
            std::time::SystemTime::now()
        ));
        (FileBoxes::open(root.join("files")), root)
    }

    fn up(name: &str, bytes: &[u8]) -> Upload {
        Upload {
            name: name.into(),
            bytes: bytes.to_vec(),
        }
    }

    fn caps(images: bool, pdfs: bool) -> SessionCapabilities {
        SessionCapabilities {
            images,
            pdfs,
            ..Default::default()
        }
    }

    #[test]
    fn sniffs_types_from_the_bytes() {
        assert_eq!(sniff(PNG), ("image/png", "png"));
        assert_eq!(sniff(&[0xFF, 0xD8, 0xFF, 0xE0]), ("image/jpeg", "jpg"));
        assert_eq!(sniff(b"GIF89a.."), ("image/gif", "gif"));
        assert_eq!(sniff(b"RIFF\0\0\0\0WEBPVP8 "), ("image/webp", "webp"));
        assert_eq!(sniff(PDF), ("application/pdf", "pdf"));
        assert_eq!(sniff(b"PK\x03\x04rest"), ("application/zip", "zip"));
        assert_eq!(sniff(b"name,size\nx,1\n"), ("text/plain", "txt"));
        // Script-capable formats are never images or inline text.
        assert_eq!(sniff(b"<svg onload=alert(1)>"), ("text/plain", "txt"));
        assert_eq!(
            content_type("0123.txt"),
            ("text/plain; charset=utf-8", false)
        );
        assert_eq!(
            sniff(b"\0\x01\x02binary"),
            ("application/octet-stream", "bin")
        );
        // A RIFF that is not WebP (e.g. WAV) is not an image.
        assert_eq!(sniff(b"RIFF\0\0\0\0WAVEfmt ").0, "application/octet-stream");
        // UTF-8 cut at the 8 KiB boundary is still text.
        let mut long = "a".repeat(8191).into_bytes();
        long.extend("é and more".as_bytes());
        assert_eq!(sniff(&long).0, "text/plain");
    }

    #[test]
    fn only_images_are_served_inline() {
        assert_eq!(content_type("ab.png"), ("image/png", true));
        assert_eq!(content_type("ab.pdf"), ("application/pdf", false));
        assert_eq!(content_type("ab.svg"), ("application/octet-stream", false));
        assert_eq!(content_type("ab"), ("application/octet-stream", false));
    }

    #[test]
    fn cleans_file_names() {
        assert_eq!(safe_name("photo.png"), "photo.png");
        assert_eq!(safe_name("../../etc/passwd"), "passwd");
        assert_eq!(
            safe_name("C:\\Users\\me\\report final.pdf"),
            "report_final.pdf"
        );
        assert_eq!(safe_name(".bashrc"), "bashrc");
        assert_eq!(safe_name("..."), "file");
        assert_eq!(safe_name(""), "file");
        assert_eq!(safe_name("a<b>\"c\".txt"), "a_b__c_.txt");
        assert_eq!(safe_name("naïve résumé.txt"), "naïve_résumé.txt");
        assert_eq!(safe_name("x\0y\n.txt"), "x_y_.txt");
        let long = format!("{}.tar.gz", "a".repeat(200));
        let short = safe_name(&long);
        assert_eq!(short.chars().count(), MAX_NAME_CHARS);
        assert!(short.ends_with(".gz"), "{short}");
    }

    #[test]
    fn enforces_the_limits() {
        assert_eq!(validate(&[]), Ok(()));
        let big = up("big.bin", &vec![1u8; MAX_FILE_BYTES + 1]);
        assert_eq!(
            validate(&[big]),
            Err(AttachmentError::FileTooLarge {
                name: "big.bin".into()
            })
        );
        let max = vec![1u8; MAX_FILE_BYTES];
        let three: Vec<Upload> = (0..3).map(|i| up(&format!("{i}"), &max)).collect();
        assert_eq!(validate(&three), Err(AttachmentError::MessageTooLarge));
        let many: Vec<Upload> = (0..=MAX_FILES).map(|i| up(&format!("{i}"), b"x")).collect();
        assert_eq!(validate(&many), Err(AttachmentError::TooMany));
        assert_eq!(
            validate(&[up("e.txt", b"")]),
            Err(AttachmentError::Empty {
                name: "e.txt".into()
            })
        );
    }

    #[test]
    fn stores_files_under_generated_ids() {
        let (boxes, root) = temp_boxes("save");
        let lead = Principal::Lead;
        let saved = boxes
            .store_uploads(
                &lead,
                vec![up("../shot.png", PNG), up("notes.md", b"# hi\n")],
            )
            .unwrap();
        assert_eq!(saved.len(), 2);
        assert_eq!(saved[0].name, "shot.png");
        assert_eq!(saved[0].mime, "image/png");
        assert!(saved[0].file.ends_with(".png") && valid_file_name(&saved[0].file));
        assert_eq!(saved[1].mime, "text/plain");
        assert_ne!(saved[0].file, saved[1].file);
        let (_, mut f) = boxes
            .open_file(&lead, crate::files::attachment_id(&saved[0].file))
            .unwrap();
        let mut bytes = Vec::new();
        f.read_to_end(&mut bytes).unwrap();
        assert_eq!(bytes, PNG);
        // Only generated ids resolve.
        assert!(boxes.open_file(&lead, "../etc/passwd").is_err());
        assert!(boxes.open_file(&lead, "shot.png").is_err());
        // Survives a JSON round trip (persisted in the conversation's events).
        let json = serde_json::to_string(&saved[0]).unwrap();
        assert_eq!(serde_json::from_str::<Attachment>(&json).unwrap(), saved[0]);
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn refused_messages_store_nothing() {
        let (boxes, root) = temp_boxes("refuse");
        let too_many: Vec<Upload> = (0..=MAX_FILES).map(|i| up(&format!("{i}"), b"x")).collect();
        assert!(boxes.store_uploads(&Principal::Lead, too_many).is_err());
        assert!(!root.join("files/boxes").exists());
        let _ = std::fs::remove_dir_all(root);
    }

    fn att(file: &str, mime: &str, size: u64) -> Attachment {
        Attachment {
            file: file.into(),
            name: file.into(),
            mime: mime.into(),
            size,
        }
    }

    #[test]
    fn plans_native_blocks_by_capability_and_size() {
        let files = [
            att("a.png", "image/png", 1000),
            att("b.pdf", "application/pdf", 1000),
            att("c.zip", "application/zip", 1000),
            att("d.png", "image/png", NATIVE_IMAGE_BYTES as u64 + 1),
        ];
        assert_eq!(plan(&files, &caps(true, true)), [true, true, false, false]);
        assert_eq!(
            plan(&files, &caps(true, false)),
            [true, false, false, false]
        );
        assert_eq!(plan(&files, &caps(false, false)), [false; 4]);
        // The total budget: the third big PDF goes to the working directory.
        let pdf = NATIVE_PDF_BYTES as u64;
        let pdfs: Vec<_> = (0..3)
            .map(|i| att(&format!("{i}.pdf"), "application/pdf", pdf))
            .collect();
        assert_eq!(plan(&pdfs, &caps(true, true)), [true, false, false]);
    }

    #[test]
    fn delivers_blocks_and_lists_the_box() {
        let (boxes, root) = temp_boxes("deliver");
        let owner = Principal::Agent("d-0a1b2c3d.a1".into());
        let saved = boxes
            .store_uploads(
                &owner,
                vec![
                    up("shot.png", PNG),
                    up("doc.pdf", PDF),
                    up("data.csv", b"a,b\n1,2\n"),
                ],
            )
            .unwrap();
        let d = deliver(&boxes, &owner, &saved, &caps(true, true));
        let png64 = base64::engine::general_purpose::STANDARD.encode(PNG);
        let pdf64 = base64::engine::general_purpose::STANDARD.encode(PDF);
        assert_eq!(
            d.blocks,
            [
                PromptBlock::Image {
                    mime: "image/png".into(),
                    data: png64
                },
                PromptBlock::Pdf { data: pdf64 }
            ]
        );
        assert!(
            d.note.contains("Attached above: shot.png, doc.pdf."),
            "{}",
            d.note
        );
        let dir = boxes.dir(&owner).unwrap();
        assert!(
            d.note
                .contains(&format!("in your file box, {}/:", dir.display())),
            "{}",
            d.note
        );
        assert!(
            d.note.contains("- data.csv (text/plain, 8 B)"),
            "{}",
            d.note
        );
        assert_eq!(std::fs::read(dir.join("data.csv")).unwrap(), b"a,b\n1,2\n");

        // Without native support every file is only listed.
        let d = deliver(&boxes, &owner, &saved, &caps(false, false));
        assert!(d.blocks.is_empty());
        assert_eq!(d.note.matches("\n- ").count(), 3);

        // A file gone from the box is reported, not fatal.
        let gone = att("0123456789abcdef0123456789abcdef.png", "image/png", 10);
        let d = deliver(&boxes, &owner, &[gone], &caps(true, true));
        assert!(d.blocks.is_empty());
        assert!(d.note.contains("could not be passed on"), "{}", d.note);
        // Another agent's box does not have them.
        let d = deliver(&boxes, &Principal::Lead, &saved, &caps(true, true));
        assert!(d.blocks.is_empty());

        assert_eq!(
            deliver(&boxes, &owner, &[], &caps(true, true)),
            Delivery::default()
        );
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn sizes_read_well() {
        assert_eq!(human_size(512), "512 B");
        assert_eq!(human_size(34 * 1024), "34 KiB");
        assert_eq!(human_size(1_258_291), "1.2 MiB");
    }
}
