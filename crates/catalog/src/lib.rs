#![forbid(unsafe_code)]
//! Melissa's app catalog: the app manifest format, its validation, and config resolution.
//!
//! A manifest is a small, human-reviewed TOML file (`manifests/<name>.toml` in the repo,
//! `/usr/share/melissa/catalog/<name>.toml` in the image). It says which containers an app
//! runs (images pinned by digest, from an allowlist of registries), its ports, environment,
//! typed config fields, volumes, ingress, probe and resources. Agents never write manifests;
//! they pick an app and may override the declared, non-secret config fields.
//!
//! Parsing is strict (`deny_unknown_fields`) and [`Manifest::validate`] checks everything a
//! renderer relies on, so rendering can't fail on a manifest that loaded. The schema is
//! documented in `docs/agent-skills/app-catalog.md`.

use std::{
    collections::{BTreeMap, BTreeSet},
    path::{Path, PathBuf},
};

use serde::{Deserialize, Serialize};
use serde_json::Value;

mod validate;

pub use validate::ImageRef;

/// The only manifest schema version so far.
pub const SCHEMA_VERSION: u32 = 1;

/// Where the image ships the catalog.
pub const DEFAULT_CATALOG_DIR: &str = "/usr/share/melissa/catalog";

/// Default domain for app ingress hosts (`<app>.<domain>`); `home.arpa` is reserved for home
/// networks (RFC 8375).
pub const DEFAULT_DOMAIN: &str = "melissa.home.arpa";

/// Default length of generated secrets (characters from a 62-letter alphabet, ~190 bits).
pub const DEFAULT_SECRET_LENGTH: usize = 32;

#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum ManifestError {
    #[error("{0}")]
    Parse(String),
    /// A field is present but wrong; the path names it (`containers[0].image`).
    #[error("{path}: {message}")]
    Invalid { path: String, message: String },
}

impl ManifestError {
    pub(crate) fn invalid(path: impl Into<String>, message: impl Into<String>) -> Self {
        Self::Invalid {
            path: path.into(),
            message: message.into(),
        }
    }
}

/// An agent's (or owner's) config overrides were rejected.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
pub enum ConfigError {
    #[error("`{0}` is not a config field of this app")]
    Unknown(String),
    #[error("`{0}` is a generated secret and cannot be set")]
    Secret(String),
    #[error("`{field}`: {message}")]
    Invalid { field: String, message: String },
}

/// One app manifest (`<name>.toml`).
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Manifest {
    /// Manifest schema version; must be [`SCHEMA_VERSION`].
    pub schema: u32,
    /// App name: a DNS label (`nextcloud`). The namespace is `app-<name>`, the host
    /// `<name>.<domain>`.
    pub name: String,
    /// The app's own version (shown to people; the image digest is what runs).
    pub version: String,
    pub description: String,
    /// Registries the images may come from (`docker.io`, `ghcr.io`). Every image must name
    /// one of them explicitly.
    pub registries: Vec<String>,
    #[serde(default)]
    pub config: Vec<ConfigField>,
    #[serde(default)]
    pub volumes: Vec<Volume>,
    pub containers: Vec<Container>,
    pub ingress: Option<Ingress>,
    /// Which config fields make up the owner's login (shown by `app-credentials`).
    pub credentials: Option<Credentials>,
}

/// A typed config field. Secrets are generated by the queen at install time and never
/// returned to agents; every other field has a default and may be overridden.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct ConfigField {
    /// Lower snake case (`admin_user`).
    pub name: String,
    #[serde(rename = "type")]
    pub kind: FieldType,
    pub description: String,
    /// Required for every type but `secret`.
    pub default: Option<Scalar>,
    /// `integer` only.
    pub min: Option<i64>,
    /// `integer` only.
    pub max: Option<i64>,
    /// `string` only (default 128).
    pub max_len: Option<usize>,
    /// `choice` only: the allowed values.
    pub options: Option<Vec<String>>,
    /// `secret` only: generated length (default [`DEFAULT_SECRET_LENGTH`], 16..=128).
    pub length: Option<usize>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum FieldType {
    String,
    Integer,
    Boolean,
    Choice,
    Secret,
}

/// A config value: TOML/JSON scalar.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(untagged)]
pub enum Scalar {
    Bool(bool),
    Int(i64),
    Str(String),
}

impl Scalar {
    /// The value as an environment variable string.
    pub fn to_env(&self) -> String {
        match self {
            Self::Bool(b) => b.to_string(),
            Self::Int(i) => i.to_string(),
            Self::Str(s) => s.clone(),
        }
    }
}

/// A persistent volume (a PVC on the `local-path` storage class for now).
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Volume {
    pub name: String,
    /// Kubernetes quantity in `Mi`, `Gi` or `Ti` (`10Gi`). local-path does not enforce it.
    pub size: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Container {
    pub name: String,
    /// `registry/repository[:tag]@sha256:<64 hex>`; the registry must be in `registries`.
    pub image: String,
    #[serde(default)]
    pub ports: Vec<Port>,
    /// Environment variables; each value names exactly one source.
    #[serde(default)]
    pub env: BTreeMap<String, EnvValue>,
    #[serde(default)]
    pub mounts: Vec<Mount>,
    pub resources: Resources,
    pub probe: Option<Probe>,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Port {
    /// IANA-style port name, at most 15 characters (`http`).
    pub name: String,
    pub port: u16,
}

/// Where an environment variable's value comes from. Exactly one field must be set.
#[derive(Debug, Clone, Default, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct EnvValue {
    /// A literal.
    pub value: Option<String>,
    /// A non-secret config field (resolved value).
    pub config: Option<String>,
    /// A secret config field (from the app's Secret, never in the pod spec).
    pub secret: Option<String>,
    /// A value Melissa knows at install time.
    pub builtin: Option<Builtin>,
}

/// The source of an [`EnvValue`], after validation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EnvSource<'a> {
    Value(&'a str),
    Config(&'a str),
    Secret(&'a str),
    Builtin(Builtin),
}

impl EnvValue {
    /// The single source; `None` if zero or several are set (rejected by validation).
    pub fn source(&self) -> Option<EnvSource<'_>> {
        let sources = [
            self.value.as_deref().map(EnvSource::Value),
            self.config.as_deref().map(EnvSource::Config),
            self.secret.as_deref().map(EnvSource::Secret),
            self.builtin.map(EnvSource::Builtin),
        ];
        let mut set = sources.into_iter().flatten();
        let first = set.next()?;
        set.next().is_none().then_some(first)
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Builtin {
    /// `<app>.<domain>`.
    IngressHost,
    /// `http://<app>.<domain>` (https once the comb has its CA).
    IngressUrl,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Mount {
    pub volume: String,
    /// Absolute path in the container.
    pub path: String,
}

/// Requests and limits; all four are required so every app is sized for small boxes.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Resources {
    /// `100m` or `1`, `0.5`.
    pub cpu_request: String,
    pub cpu_limit: String,
    /// `256Mi`, `1Gi`.
    pub memory_request: String,
    pub memory_limit: String,
}

/// HTTP probe, used for startup, readiness and liveness.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Probe {
    /// Absolute path (`/status.php`).
    pub path: String,
    /// Name of one of the container's ports.
    pub port: String,
    /// Send the ingress host as `Host` (apps that check trusted domains).
    #[serde(default)]
    pub ingress_host_header: bool,
    /// How long the first start (install, migrations) may take before the pod is restarted.
    #[serde(default = "default_startup_secs")]
    pub startup_timeout_secs: u32,
    #[serde(default = "default_period_secs")]
    pub period_secs: u32,
}

fn default_startup_secs() -> u32 {
    300
}

fn default_period_secs() -> u32 {
    10
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Ingress {
    /// Container port name the ingress routes to.
    pub port: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Credentials {
    /// A `string` config field: the login name.
    pub user: Option<String>,
    /// A `secret` config field: the password.
    pub password: String,
}

/// Config values for one install: every non-secret field (defaults + overrides) and the
/// secrets to generate. Secret values themselves never pass through here.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedConfig {
    pub values: BTreeMap<String, Scalar>,
    /// Secret field name → generated length.
    pub secrets: BTreeMap<String, usize>,
}

impl Manifest {
    /// Parse and validate. `source` names the file in errors.
    pub fn parse(text: &str) -> Result<Self, ManifestError> {
        let manifest: Self =
            toml::from_str(text).map_err(|e| ManifestError::Parse(e.to_string()))?;
        manifest.validate()?;
        Ok(manifest)
    }

    /// Kubernetes namespace of this app.
    pub fn namespace(&self) -> String {
        namespace_of(&self.name)
    }

    /// Name of the Secret holding the generated secrets.
    pub fn secret_name(&self) -> String {
        format!("{}-secrets", self.name)
    }

    /// `<name>.<domain>`.
    pub fn host(&self, domain: &str) -> String {
        format!("{}.{domain}", self.name)
    }

    pub fn field(&self, name: &str) -> Option<&ConfigField> {
        self.config.iter().find(|f| f.name == name)
    }

    /// Defaults merged with `overrides` (a JSON object of field → value). Only declared,
    /// non-secret fields may be overridden, with values of the right type and range.
    pub fn resolve_config(
        &self,
        overrides: &serde_json::Map<String, Value>,
    ) -> Result<ResolvedConfig, ConfigError> {
        for (key, value) in overrides {
            let field = self
                .field(key)
                .ok_or_else(|| ConfigError::Unknown(key.clone()))?;
            if field.kind == FieldType::Secret {
                return Err(ConfigError::Secret(key.clone()));
            }
            field.check_json(value)?;
        }
        let mut values = BTreeMap::new();
        let mut secrets = BTreeMap::new();
        for field in &self.config {
            if field.kind == FieldType::Secret {
                secrets.insert(
                    field.name.clone(),
                    field.length.unwrap_or(DEFAULT_SECRET_LENGTH),
                );
                continue;
            }
            let value = match overrides.get(&field.name) {
                Some(v) => field.check_json(v)?,
                // Validation guarantees a default for non-secret fields.
                None => field.default.clone().ok_or_else(|| ConfigError::Invalid {
                    field: field.name.clone(),
                    message: "no default".into(),
                })?,
            };
            values.insert(field.name.clone(), value);
        }
        Ok(ResolvedConfig { values, secrets })
    }
}

impl ConfigField {
    /// Check a JSON override against this field's type and limits.
    fn check_json(&self, value: &Value) -> Result<Scalar, ConfigError> {
        let bad = |message: String| ConfigError::Invalid {
            field: self.name.clone(),
            message,
        };
        let scalar = match (self.kind, value) {
            (FieldType::Boolean, Value::Bool(b)) => Scalar::Bool(*b),
            (FieldType::Integer, Value::Number(n)) => Scalar::Int(
                n.as_i64()
                    .ok_or_else(|| bad("must be a whole number".into()))?,
            ),
            (FieldType::String | FieldType::Choice, Value::String(s)) => Scalar::Str(s.clone()),
            (kind, _) => return Err(bad(format!("must be a {}", kind.as_str()))),
        };
        self.check(&scalar).map_err(bad)?;
        Ok(scalar)
    }

    /// Range/shape check for a value of the right type.
    pub(crate) fn check(&self, value: &Scalar) -> Result<(), String> {
        match (self.kind, value) {
            (FieldType::Integer, Scalar::Int(i)) => {
                if self.min.is_some_and(|m| *i < m) || self.max.is_some_and(|m| *i > m) {
                    return Err(format!(
                        "must be between {} and {}",
                        self.min.map_or("-inf".into(), |m| m.to_string()),
                        self.max.map_or("inf".into(), |m| m.to_string())
                    ));
                }
                Ok(())
            }
            (FieldType::String, Scalar::Str(s)) => {
                let max = self.max_len.unwrap_or(128);
                if s.is_empty() || s.chars().count() > max {
                    return Err(format!("must be 1 to {max} characters"));
                }
                // Values end up in environment variables; keep them to printable text.
                if s.chars().any(char::is_control) {
                    return Err("must not contain control characters".into());
                }
                Ok(())
            }
            (FieldType::Choice, Scalar::Str(s)) => {
                let options = self.options.as_deref().unwrap_or_default();
                if options.iter().any(|o| o == s) {
                    Ok(())
                } else {
                    Err(format!("must be one of {}", options.join(", ")))
                }
            }
            (FieldType::Boolean, Scalar::Bool(_)) => Ok(()),
            (kind, _) => Err(format!("must be a {}", kind.as_str())),
        }
    }
}

impl FieldType {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::String => "string",
            Self::Integer => "integer",
            Self::Boolean => "boolean",
            Self::Choice => "choice",
            Self::Secret => "secret",
        }
    }
}

/// Is `name` a well-formed app name (what manifests' `name` must be)?
pub fn valid_app_name(name: &str) -> bool {
    validate::dns_label(name, 40).is_ok()
}

/// `app-<name>`: the namespace of an app.
pub fn namespace_of(app: &str) -> String {
    format!("app-{app}")
}

/// A directory of manifests. Files must be named `<name>.toml`.
#[derive(Debug, Clone, Default)]
pub struct Catalog {
    pub apps: BTreeMap<String, Manifest>,
    /// Files that failed to load, with the reason. A broken manifest never hides the others.
    pub errors: Vec<(PathBuf, String)>,
}

impl Catalog {
    /// Load every `*.toml` in `dir`. A missing directory is an empty catalog.
    pub fn load_dir(dir: &Path) -> Self {
        let mut catalog = Self::default();
        let Ok(entries) = std::fs::read_dir(dir) else {
            return catalog;
        };
        let mut files: Vec<PathBuf> = entries
            .filter_map(|e| e.ok().map(|e| e.path()))
            .filter(|p| p.extension().is_some_and(|e| e == "toml"))
            .collect();
        files.sort();
        let mut seen = BTreeSet::new();
        for path in files {
            match load_file(&path) {
                Ok(m) if seen.insert(m.name.clone()) => {
                    catalog.apps.insert(m.name.clone(), m);
                }
                Ok(m) => catalog
                    .errors
                    .push((path, format!("duplicate app name `{}`", m.name))),
                Err(e) => catalog.errors.push((path, e)),
            }
        }
        catalog
    }

    pub fn get(&self, name: &str) -> Option<&Manifest> {
        self.apps.get(name)
    }
}

fn load_file(path: &Path) -> Result<Manifest, String> {
    // Manifests are small; refuse anything that isn't.
    const MAX_BYTES: u64 = 64 * 1024;
    let size = std::fs::metadata(path).map_err(|e| e.to_string())?.len();
    if size > MAX_BYTES {
        return Err(format!("larger than {MAX_BYTES} bytes"));
    }
    let text = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
    let manifest = Manifest::parse(&text).map_err(|e| e.to_string())?;
    let stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or_default();
    if stem != manifest.name {
        return Err(format!(
            "file name must be `{}.toml` (the app's name)",
            manifest.name
        ));
    }
    Ok(manifest)
}

